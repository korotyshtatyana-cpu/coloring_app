/// Enum representing the available contour categories.
enum ContourCategory {
  /// All categories (UI-only, not stored on contours).
  all,

  /// Animals category.
  animals,

  /// Nature category.
  nature,

  /// Fantasy category.
  fantasy,

  /// Mandala category.
  mandala,

  /// Transport category.
  transport,

  /// Cities category.
  cities,

  /// People category.
  people,

  /// Flowers category.
  flowers,

  /// Patterns category.
  patterns,

  /// Abstract category.
  abstract,
}
